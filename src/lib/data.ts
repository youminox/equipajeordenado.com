/**
 * Server-only data layer. Imports the full posts dataset (20 MB) — never
 * import this module from a "use client" component; use ./utils or
 * ./airlines instead.
 */
import fs from "node:fs";
import path from "node:path";
import postsData from "../../data/posts.json";
import categoriesData from "../../data/categories.json";
import pagesData from "../../data/pages.json";
import seoIndex from "../../data/seo-index.json";
import type { Post, Category } from "./types";

export * from "./utils";

/* ------------------------------------------------------------------ */
/* SEO index: pruning (noindex) + consolidation (301 merges)           */
/* Generated by scripts/seo-audit.py                                   */
/* ------------------------------------------------------------------ */

const MERGES: Record<string, string> = seoIndex.merges as Record<string, string>;
const NOINDEX = new Set<string>(seoIndex.noindex as string[]);
const OFF_TOPIC_CATEGORIES = new Set<string>(
  seoIndex.offTopicCategories as string[]
);

/* ------------------------------------------------------------------ */
/* Editorial overrides: data/editorial/<slug>.json                     */
/* Rewritten or brand-new articles. Same slug => replaces the original. */
/* ------------------------------------------------------------------ */

interface EditorialEntry {
  slug: string;
  category: string;
  title: string;
  seoTitle?: string;
  description?: string;
  excerpt?: string;
  featuredImageUrl?: string;
  date?: string;
  modified?: string;
  content: string;
}

function estimateReadTime(html: string): string {
  const words = html.replace(/<[^>]*>/g, " ").split(/\s+/).filter(Boolean).length;
  return `${Math.max(1, Math.round(words / 220))} min`;
}

function loadEditorial(): EditorialEntry[] {
  const dir = path.join(process.cwd(), "data", "editorial");
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")) as EditorialEntry);
}

const rawCategories: Category[] = categoriesData as Category[];
const categoryNameBySlug = new Map(rawCategories.map((c) => [c.slug, c.name]));

function buildPosts(): Post[] {
  const base = (postsData as Post[]).filter((p) => !MERGES[p.slug]);
  const bySlug = new Map(base.map((p) => [p.slug, p]));
  let nextId = 9_000_000;

  for (const e of loadEditorial()) {
    const original = bySlug.get(e.slug);
    const categoryName = categoryNameBySlug.get(e.category) || original?.categoryName || e.category;
    const merged: Post = {
      id: original?.id ?? nextId++,
      title: e.title,
      slug: e.slug,
      category: e.category,
      categoryName,
      categories: original?.categories ?? [{ slug: e.category, name: categoryName }],
      date: e.date || original?.date || e.modified || "",
      modified: e.modified || original?.modified || "",
      readTime: estimateReadTime(e.content),
      content: e.content,
      excerpt: e.excerpt || original?.excerpt || "",
      featuredImageId: original?.featuredImageId ?? null,
      featuredImageUrl: e.featuredImageUrl || original?.featuredImageUrl || "",
      type: "post",
      status: "publish",
      seoTitle: e.seoTitle,
      description: e.description,
      editorial: true,
    };
    if (original) {
      base[base.indexOf(original)] = merged;
    } else {
      base.unshift(merged);
    }
    bySlug.set(e.slug, merged);
  }
  return base;
}

const posts: Post[] = buildPosts();
const postBySlug = new Map(posts.map((p) => [p.slug, p]));
const pages: Post[] = pagesData as Post[];

export function isPostIndexable(post: Post): boolean {
  return !NOINDEX.has(post.slug);
}

export function isCategoryIndexable(slug: string): boolean {
  return !OFF_TOPIC_CATEGORIES.has(slug);
}

const indexablePosts: Post[] = posts.filter(isPostIndexable);

/** Returns the 301 target path for a merged (consolidated) slug, if any. */
export function getMergeTarget(slug: string): string | undefined {
  return MERGES[slug];
}

/** Every live post (indexable or not). Used for static params. */
export function getAllPosts(): Post[] {
  return posts;
}

/** Posts that should be indexed, linked internally and listed in the sitemap. */
export function getIndexablePosts(): Post[] {
  return indexablePosts;
}

export function getAllPages(): Post[] {
  return pages;
}

export function getPageBySlug(slug: string): Post | undefined {
  return pages.find((p) => p.slug === slug);
}

export function getPostBySlug(slug: string): Post | undefined {
  return postBySlug.get(slug);
}

/** Category listing: indexable posts first, editorial (rewritten) first among them. */
export function getPostsByCategorySlug(categorySlug: string): Post[] {
  const inCat = posts.filter(
    (p) =>
      p.category === categorySlug ||
      p.categories.some((c) => c.slug === categorySlug)
  );
  const rank = (p: Post) => (p.editorial ? 0 : isPostIndexable(p) ? 1 : 2);
  return inCat
    .map((p, i) => ({ p, i }))
    .sort((a, b) => rank(a.p) - rank(b.p) || a.i - b.i)
    .map(({ p }) => p);
}

const FEATURED_SLUGS = [
  "que-se-considera-como-equipaje-de-mano",
  "que-liquidos-estan-permitidos-en-el-equipaje-de-mano",
  "cuales-son-las-restricciones-de-peso-para-el-equipaje-de-mano",
  "seguro-para-maletas-de-viaje",
  "como-asegurar-tu-equipaje-de-mano-contra-robos",
  "cuales-son-las-dimensiones-estandar-del-equipaje-de-mano",
  "como-elegir-el-mejor-equipaje-de-mano",
  "como-maximizar-el-espacio-en-el-equipaje-de-mano",
];

export function getFeaturedPosts(limit: number = 6): Post[] {
  const featured: Post[] = [];
  for (const slug of FEATURED_SLUGS) {
    const found = postBySlug.get(slug);
    if (found && found.featuredImageUrl && isPostIndexable(found)) featured.push(found);
    if (featured.length >= limit) return featured;
  }
  for (const p of indexablePosts) {
    if (p.featuredImageUrl && !featured.some((f) => f.id === p.id)) {
      featured.push(p);
      if (featured.length >= limit) break;
    }
  }
  return featured;
}

export function getRecentPosts(limit: number = 12): Post[] {
  const featuredIds = new Set(FEATURED_SLUGS);
  const catCounts = new Map<string, number>();
  const selected: Post[] = [];

  for (const p of indexablePosts) {
    if (featuredIds.has(p.slug)) continue;
    if (!isCategoryIndexable(p.category)) continue;
    const count = catCounts.get(p.category) || 0;
    if (count >= 4) continue;
    selected.push(p);
    catCounts.set(p.category, count + 1);
    if (selected.length >= limit) break;
  }

  return selected.length > 0 ? selected : indexablePosts.slice(0, limit);
}

function rotateFrom(list: Post[], post: Post, limit: number, offset = 1): Post[] {
  if (list.length <= 1) return [];
  const currentIndex = list.findIndex((p) => p.id === post.id);
  const startIndex = currentIndex >= 0 ? currentIndex + offset : 0;
  const out: Post[] = [];
  for (let i = 0; i < list.length && out.length < limit; i++) {
    const candidate = list[(startIndex + i) % list.length];
    if (candidate.id !== post.id && !out.includes(candidate)) out.push(candidate);
  }
  return out;
}

/** Related posts (same category, indexable only). Falls back to on-topic guides. */
export function getRelatedPosts(post: Post, limit: number = 4): Post[] {
  const sameCategory = indexablePosts.filter((p) => p.category === post.category);
  const related = rotateFrom(sameCategory, post, limit);
  if (related.length >= limit) return related;
  const filler = getFeaturedPosts(limit + 2).filter(
    (p) => p.id !== post.id && !related.some((r) => r.id === p.id)
  );
  return [...related, ...filler].slice(0, limit);
}

export function getContextualRelatedPosts(post: Post, limit: number = 3): Post[] {
  const sameCategory = indexablePosts.filter((p) => p.category === post.category);
  return rotateFrom(sameCategory, post, limit, 5);
}

export function getAllCategories(): Category[] {
  return [...rawCategories].sort((a, b) => b.count - a.count);
}

/** On-topic categories (indexed, in nav and sitemap) with live post counts. */
export function getIndexableCategories(): Category[] {
  return getAllCategories()
    .filter((c) => isCategoryIndexable(c.slug))
    .map((c) => ({
      ...c,
      count: indexablePosts.filter((p) => p.category === c.slug).length,
    }));
}

export function getCategoryBySlug(slug: string): Category | undefined {
  return rawCategories.find((c) => c.slug === slug);
}

/** Slim post shape for client components (no HTML content). */
export type PostCard = Pick<
  Post,
  "id" | "title" | "slug" | "category" | "categoryName" | "readTime" | "excerpt" | "featuredImageUrl"
>;

export function toPostCard(p: Post): PostCard {
  return {
    id: p.id,
    title: p.title,
    slug: p.slug,
    category: p.category,
    categoryName: p.categoryName,
    readTime: p.readTime,
    excerpt: p.excerpt,
    featuredImageUrl: p.featuredImageUrl,
  };
}
